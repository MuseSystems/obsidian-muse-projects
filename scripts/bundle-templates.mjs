import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const templatesRoot = 'templates';
const target = 'src/bundledTemplates.gen.ts';

function relativePath(prefix, name) {
	const rel = prefix ? `${prefix}/${name}` : name;
	const parts = rel.split('/');
	if (parts.some((part) => part === '' || part === '.' || part === '..')) {
		throw new Error(`Refusing template path ${rel}`);
	}
	return rel;
}

function listTemplates(dir, prefix) {
	const files = [];
	for (const name of readdirSync(dir)) {
		if (name === '.DS_Store' || (name.startsWith('.') && name !== '.gitkeep') || name.endsWith('~')) {
			continue;
		}
		const full = path.join(dir, name);
		const rel = relativePath(prefix, name);
		if (statSync(full).isDirectory()) {
			files.push(...listTemplates(full, rel));
			continue;
		}
		files.push({ path: rel, content: readFileSync(full, 'utf8') });
	}
	files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
	return files;
}

function render(files) {
	const rows = files.map(
		(file) => `\t{ path: ${JSON.stringify(file.path)}, content: ${JSON.stringify(file.content)} },`,
	);
	return `/* Generated by scripts/bundle-templates.mjs. Edit templates/ and rebuild. */\nimport type { BundledTemplateFile } from './templateSeedPlan';\n\nexport const BUNDLED_TEMPLATES: readonly BundledTemplateFile[] = [\n${rows.join('\n')}\n];\n`;
}

/** Write the embedded template module when templates/ changed. */
export function writeBundledTemplates() {
	const next = render(listTemplates(templatesRoot, ''));
	const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
	if (current === next) return false;
	writeFileSync(target, next);
	return true;
}

const invoked =
	process.argv[1] !== undefined && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (invoked) {
	writeBundledTemplates();
}
